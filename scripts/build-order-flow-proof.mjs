import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {LEVELS,validateLevel,rayIds,solve} from '../public/play/games/order-flow-model.mjs';
export function buildCertificate(level){
 validateLevel(level);
 const answer=solve(level);if(!answer||answer.moves!==level.cars.length)throw Error('No minimum-length clearing path');
 const rank=new Map(answer.path.map((id,i)=>[id,i])),depth=new Map();
 for(const id of answer.path){
  const dependencies=rayIds(level,level.cars[id-1]);
  if(dependencies.some(d=>rank.get(d)>=rank.get(id)))throw Error('Dependency cycle');
  depth.set(id,1+Math.max(0,...dependencies.map(d=>depth.get(d))));
 }
 return {signature:JSON.stringify({cols:level.cols,rows:level.rows,cars:level.cars}),order:answer.path,minimum:answer.moves,depth:Math.max(...depth.values())};
}
export const buildProofs=()=>LEVELS.map(buildCertificate);
export const serializeProofs=p=>'// Generated by scripts/build-order-flow-proof.mjs.\nexport const PROOFS = '+JSON.stringify(p)+';\n';
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1]){
 const proofs=buildProofs();writeFileSync(new URL('../public/play/games/order-flow-proof-data.mjs',import.meta.url),serializeProofs(proofs));
 console.log(proofs.map((p,i)=>({level:i+1,cars:p.minimum,chain:p.depth})));
}
