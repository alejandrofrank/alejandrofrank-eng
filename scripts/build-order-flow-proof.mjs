import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {LEVELS,initialState,legalMoves,move} from '../public/play/games/order-flow-model.mjs';
import {positionKey,levelSignature} from '../public/play/games/order-flow-position.mjs';

// Enumerate every reachable settled position, including losing branches.
// Reverse BFS computes the exact shortest distance from each position to a win.
// No heuristic, random sample, or search cutoff is accepted as a proof.
export function buildCertificate(level){
 const rules={...level,budget:Number.MAX_SAFE_INTEGER};
 const states=[initialState(rules)],indices=new Map([[positionKey(states[0]),0]]),edges=[],parents=[[]];
 for(let i=0;i<states.length;i++){
  edges[i]=[];
  for(const id of legalMoves(rules,states[i])){
   const state=move(rules,states[i],id,{trace:false}).state,key=positionKey(state);
   let next=indices.get(key);
   if(next===undefined){next=states.length;indices.set(key,next);states.push(state);parents.push([]);}
   edges[i].push([id,next]);parents[next].push(i);
  }
  if(states.length>100000)throw Error('Proof too large; do not ship an incomplete certificate');
 }
 const distance=states.map(s=>s.status==='won'?0:-1),queue=distance.flatMap((d,i)=>d===0?[i]:[]);
 for(let n=0;n<queue.length;n++)for(const p of parents[queue[n]])if(distance[p]<0){distance[p]=distance[queue[n]]+1;queue.push(p);}
 if(distance[0]!==level.par||distance[0]>level.budget)throw Error('Invalid minimum or budget: '+level.title);
 return {signature:levelSignature(level),states:states.length,transitions:edges.reduce((n,e)=>n+e.length,0),positions:Object.fromEntries(states.map((s,i)=>[positionKey(s),[distance[i],...edges[i].filter(([,j])=>distance[i]>0&&distance[j]===distance[i]-1).map(([id])=>id)]]))};
}
export const buildProofs=()=>LEVELS.map(buildCertificate);
export const serializeProofs=proofs=>'// Generated by scripts/build-order-flow-proof.mjs. Do not edit by hand.\nexport const PROOFS = '+JSON.stringify(proofs)+';\n';
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1]){
 const proofs=buildProofs();writeFileSync(new URL('../public/play/games/order-flow-proof-data.mjs',import.meta.url),serializeProofs(proofs));
 console.log('Certified '+proofs.length+' levels, '+proofs.reduce((n,p)=>n+p.states,0)+' positions and '+proofs.reduce((n,p)=>n+p.transitions,0)+' transitions.');
}
